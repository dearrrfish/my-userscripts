import test from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { runCli, hash } from '../dist/index.js';
import { fixtureObservationDigest } from '@fm/contracts';
const repo = path.resolve(import.meta.dirname, '../../..');
const target = 'firemonkey-3.9-firefox-157.0';
const source = await fs.readFile(path.join(repo, 'fixtures/cli/safe.user.js'), 'utf8');
async function workspace() {
  const dir = await fs.mkdtemp(path.join(repo, '.fm/w3-integration-'));
  await fs.writeFile(path.join(dir, 'input.user.js'), source);
  return dir;
}
async function observe(dir, runId) {
  const fixture = await runCli(['fixtures', 'template', '--run', runId], { cwd: dir });
  assert.equal(fixture.code, 0, JSON.stringify(fixture));
  const observation = JSON.parse(await fs.readFile(fixture.template));
  observation.verifier = 'Synthetic integration observer; not actual FireMonkey evidence';
  observation.cases.forEach(c => { c.status = 'passed'; c.command = 'Deliberate isolated synthetic observation; never execute this text'; c.evidence = 'Synthetic validation of binding and state transitions only'; });
  observation.evidenceDigest = fixtureObservationDigest(observation);
  await fs.writeFile(path.join(dir, 'fixture-observation.json'), JSON.stringify(observation));
  const recorded = await runCli(['fixtures', 'record', '--run', runId, '--file', 'fixture-observation.json'], { cwd: dir });
  assert.equal(recorded.code, 3, JSON.stringify(recorded));
  const browser = await runCli(['acceptance', 'template', '--run', runId], { cwd: dir });
  assert.equal(browser.code, 0, JSON.stringify(browser));
  const receipt = JSON.parse(await fs.readFile(browser.template));
  receipt.verifier = observation.verifier;
  receipt.perStepResults.forEach(s => { s.status = 'passed'; s.evidence = 'Synthetic test, no actual Firefox or FireMonkey behavior claimed'; });
  receipt.evidenceDigest = hash(JSON.stringify(receipt.perStepResults, null, 2) + '\n');
  await fs.writeFile(path.join(dir, 'browser-observation.json'), JSON.stringify(receipt));
  const accepted = await runCli(['acceptance', 'record', '--run', runId, '--file', 'browser-observation.json'], { cwd: dir });
  assert.equal(accepted.code, 0, JSON.stringify(accepted));
  assert.equal(accepted.state, 'complete');
  return { observation, receipt };
}
test('fixture and browser observations combine, survive verify, and reject actor tampering', async () => {
  const dir = await workspace();
  const run = await runCli(['convert', '--input', 'input.user.js', '--output', 'candidate.user.js', '--target', target], { cwd: dir });
  assert.equal(run.code, 0, JSON.stringify(run));
  const pending = await runCli(['evolve', 'propose', '--run', run.runId], { cwd: dir });
  assert.equal(pending.code, 2, JSON.stringify(pending));
  assert.match(pending.error, /owned source checkout/);
  const { observation } = await observe(dir, run.runId);
  const verified = await runCli(['verify', '--run', run.runId, '--static'], { cwd: dir });
  assert.equal(verified.code, 0, JSON.stringify(verified));
  assert.equal(verified.state, 'complete');
  const noDraft = await runCli(['evolve', 'propose', '--run', run.runId], { cwd: dir });
  assert.equal(noDraft.code, 2, JSON.stringify(noDraft));
  assert.match(noDraft.error, /owned source checkout/);
  observation.verifier = 'Altered actor without updated digest';
  await fs.writeFile(path.join(dir, 'tampered.json'), JSON.stringify(observation));
  assert.equal((await runCli(['fixtures', 'record', '--run', run.runId, '--file', 'tampered.json'], { cwd: dir })).code, 2);
  assert.equal((await runCli(['verify', '--run', run.runId, '--static'], { cwd: dir })).code, 0);
});
test('release freezes a derived candidate requiring fresh evidence before stable output', async () => {
  const dir = await workspace();
  const license = 'Synthetic test copyright holder grants MIT permission.\n';
  await fs.writeFile(path.join(dir, 'LICENSE.synthetic'), license);
  const config = { schemaVersion: 1, outputRoot: 'outputs', targetProfile: target, projects: [{ id: 'synthetic', upstream: { kind: 'local', path: '.' }, scripts: [{ id: 'synthetic', sourcePath: 'input.user.js', sourceManager: 'unknown', outputPath: 'synthetic.user.js', identity: { name: 'CLI synthetic fixture', namespace: 'fm-tests' }, acceptance: { checklistId: 'synthetic-runtime' }, publish: { mode: 'local', baseUrl: 'https://example.test/scripts/', licenseEvidence: { kind: 'official', reference: 'LICENSE.synthetic', hash: hash(license), description: 'Isolated synthetic MIT permission evidence' }, versionMajor: 2, initialRevision: 0 } }] }] };
  await fs.writeFile(path.join(dir, 'config.json'), JSON.stringify(config));
  const run = await runCli(['convert', '--input', 'input.user.js', '--output', 'outputs/synthetic.user.js', '--target', target, '--config', 'config.json', '--script-id', 'synthetic'], { cwd: dir });
  assert.equal(run.code, 0, JSON.stringify(run));
  await observe(dir, run.runId);
  const args = ['prepare-release', '--config', 'config.json', '--script', 'synthetic'];
  const candidate = await runCli([...args, '--run', run.runId, '--stage', 'candidate'], { cwd: dir });
  assert.equal(candidate.code, 0, JSON.stringify(candidate));
  assert.notEqual(candidate.runId, run.runId);
  assert.equal(candidate.state, 'pending-browser');
  assert.equal(candidate.version, '2.0');
  const original = JSON.parse(await fs.readFile(run.json)).result;
  const derived = JSON.parse(await fs.readFile(candidate.json)).result;
  assert.equal(derived.inputHash, original.inputHash);
  assert.notEqual(derived.outputHash, original.outputHash);
  const frozen = await fs.readFile(candidate.output, 'utf8');
  assert.match(frozen, /@version\s+2\.0/);
  const early = await runCli([...args, '--run', candidate.runId, '--stage', 'finalize'], { cwd: dir });
  assert.equal(early.code, 3, JSON.stringify(early));
  const stale = await runCli(['fixtures', 'record', '--run', candidate.runId, '--file', 'fixture-observation.json'], { cwd: dir });
  assert.equal(stale.code, 2);
  await observe(dir, candidate.runId);
  const final = await runCli([...args, '--run', candidate.runId, '--stage', 'finalize'], { cwd: dir });
  assert.equal(final.code, 0, JSON.stringify(final));
  const manifest = JSON.parse(await fs.readFile(final.releaseManifest));
  assert.equal(manifest.outputHash, derived.outputHash);
  assert.equal(await fs.readFile(path.join(dir, 'artifacts/release/synthetic.user.js'), 'utf8'), frozen);
});
